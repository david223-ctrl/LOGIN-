function renderData(data) {
  document.getElementById('userName').innerText = data.name;
  document.getElementById('userAvatar').src = data.avatar;
  document.getElementById('userLevel').innerText = `LVL ${data.level}`;
  document.getElementById('userCustomUrl').innerText = data.customUrl;

  document.getElementById('accLogin').innerText = data.login;
  document.getElementById('accPass').innerText = data.password;

  const statusDot = document.querySelector('.status-dot');
  const statusText = document.getElementById('statusText');
  if (data.online) {
    statusDot.className = 'status-dot online';
    statusText.innerText = 'В сети';
  } else {
    statusDot.className = 'status-dot offline';
    statusText.innerText = 'Не в сети';
  }

  const gaugeFill = document.getElementById('gaugeFill');
  const trustValue = document.getElementById('trustValue');
  const trustLabel = document.getElementById('trustLabel');

  const offset = 314 - (314 * data.trustScore) / 100;
  gaugeFill.style.strokeDashoffset = offset;
  trustValue.innerText = `${data.trustScore}%`;

  if (data.trustScore > 80) {
    gaugeFill.style.stroke = '#00ff85';
    trustLabel.innerText = 'Надежный';
  } else {
    gaugeFill.style.stroke = '#ff2a5f';
    trustLabel.innerText = 'Подозрительный';
  }

  setBan('vacStatus', data.vac);
  setBan('gameBanStatus', data.gameBan);
  setBan('tradeBanStatus', data.tradeBan);
  setBan('communityStatus', data.community);

  document.getElementById('invValue').innerText = data.invValue;
  document.getElementById('gamesCount').innerText = data.gamesCount;
  document.getElementById('totalHours').innerText = data.totalHours;
  document.getElementById('accAge').innerText = `${data.accAge} лет`;

  document.getElementById('id64').innerText = data.id64;
  document.getElementById('id3').innerText = data.id3;

  const gamesList = document.getElementById('gamesList');
  gamesList.innerHTML = '';
  data.games.forEach(g => {
    const gameName = typeof g === 'string' ? g : g.name;
    const gameHours = typeof g === 'string' ? '' : g.hours;
    gamesList.innerHTML += `
      <div class="game-row">
        <span>${gameName}</span>
        <span class="game-hours">${gameHours}</span>
      </div>
    `;
  });
}

function setBan(id, isBanned) {
  const el = document.getElementById(id);
  if (isBanned) {
    el.className = 'danger';
    el.innerText = '❌ ЕСТЬ БАН';
  } else {
    el.className = 'safe';
    el.innerText = '✓ НЕТ';
  }
}

function copyValue(elementId, label) {
  const text = document.getElementById(elementId).innerText;
  navigator.clipboard.writeText(text);
  alert(`${label} скопирован в буфер обмена: ${text}`);
}

