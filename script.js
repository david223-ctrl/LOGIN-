// Interactive Skull Eyes Mouse Tracking
document.addEventListener('mousemove', (e) => {
  const leftPupil = document.getElementById('leftPupil');
  const rightPupil = document.getElementById('rightPupil');
  if(leftPupil && rightPupil) {
    moveEye(leftPupil, 37, 46, e.clientX, e.clientY);
    moveEye(rightPupil, 63, 46, e.clientX, e.clientY);
  }
});

function moveEye(pupil, eyeX, eyeY, mouseX, mouseY) {
  const rect = pupil.getBoundingClientRect();
  const eyeCenterX = rect.left + rect.width / 2;
  const eyeCenterY = rect.top + rect.height / 2;
  
  const angle = Math.atan2(mouseY - eyeCenterY, mouseX - eyeCenterX);
  const distance = Math.min(3.5, Math.hypot(mouseX - eyeCenterX, mouseY - eyeCenterY) / 40);
  
  const moveX = Math.cos(angle) * distance;
  const moveY = Math.sin(angle) * distance;
  
  pupil.style.transform = `translate(${moveX}px, ${moveY}px)`;
}

